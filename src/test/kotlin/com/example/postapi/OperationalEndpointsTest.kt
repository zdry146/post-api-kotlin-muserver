    // ============ RateLimit ============

    @Test
    fun `rate limit - allows first N requests then returns 429`() {
        // 独立 server 用低 limit (3/sec) 测快速触限
        val rateLimit = RateLimitHandler(requestsPerSecond = 3)
        val postRepository = PostRepository(dataSource)
        val postService = PostService(postRepository)
        val postHandler = PostHandler(postService)
        val cleanupJob = CleanupJob(postRepository)
        val adminHandler = AdminHandler(cleanupJob)

        val builder = io.muserver.MuServerBuilder.httpServer().withHttpPort(0)
        builder.addHandler(rateLimit)
        val routes = postHandler.register() + adminHandler.register()
        routes.forEach { builder.addHandler(it) }
        val s = builder.start()
        val uri = "http://localhost:${s.uri().port}"
        val localClient = OkHttpClient.Builder().build()

        try {
            // 先 create 一篇 post，然后 like 多次
            localClient.newCall(
                Request.Builder().url("$uri/api/posts")
                    .post("""{"title":"RL","content":"X","authorName":"A"}""".toRequestBody(jsonMt))
                    .build()
            ).execute().use { assertThat(it.code).isEqualTo(200) }

            // POST /api/posts/1/like × 5 — limit 是 3，应该至少收到一个 429
            var got429 = false
            for (i in 1..5) {
                val resp = localClient.newCall(
                    Request.Builder().url("$uri/api/posts/1/like").post("".toRequestBody(jsonMt)).build()
                ).execute()
                resp.use {
                    if (it.code == 429) {
                        got429 = true
                        assertThat(it.header("Retry-After")).isEqualTo("1")
                    }
                }
            }
            assertThat(got429).`as`("Should have at least one 429 within burst of 5 against limit 3").isTrue
        } finally {
            s.stop()
            localClient.dispatcher.executorService.shutdown()
            localClient.connectionPool.evictAll()
        }
    }

    @Test
    fun `rate limit - does NOT limit GET paths`() {
        val rateLimit = RateLimitHandler(requestsPerSecond = 2)
        val postRepository = PostRepository(dataSource)
        val postService = PostService(postRepository)
        val postHandler = PostHandler(postService)

        val builder = io.muserver.MuServerBuilder.httpServer().withHttpPort(0)
        builder.addHandler(rateLimit)
        postHandler.register().forEach { builder.addHandler(it) }
        val s = builder.start()
        val uri = "http://localhost:${s.uri().port}"
        val localClient = OkHttpClient.Builder().build()

        try {
            // GET 路径 × 10 — 永远不应该 429
            for (i in 1..10) {
                val resp = localClient.newCall(
                    Request.Builder().url("$uri/api/posts/published?page=0&size=10").get().build()
                ).execute()
                resp.use {
                    assertThat(it.code).isNotEqualTo(429)
                }
            }
        } finally {
            s.stop()
            localClient.dispatcher.executorService.shutdown()
            localClient.connectionPool.evictAll()
        }
    }

    @Test
    fun `rate limit - disabled when env RATE_LIMIT_ENABLED false`() {
        // 用 enabled=false 的 handler，验证即使 burst 也不会 429
        val rateLimit = RateLimitHandler(requestsPerSecond = 1, enabled = false)
        val postRepository = PostRepository(dataSource)
        val postService = PostService(postRepository)
        val postHandler = PostHandler(postService)

        val builder = io.muserver.MuServerBuilder.httpServer().withHttpPort(0)
        builder.addHandler(rateLimit)
        postHandler.register().forEach { builder.addHandler(it) }
        val s = builder.start()
        val uri = "http://localhost:${s.uri().port}"
        val localClient = OkHttpClient.Builder().build()

        try {
            localClient.newCall(
                Request.Builder().url("$uri/api/posts")
                    .post("""{"title":"RLOff","content":"X","authorName":"A"}""".toRequestBody(jsonMt))
                    .build()
            ).execute().use { assertThat(it.code).isEqualTo(200) }

            // 10 次 like — disabled 永远 200
            for (i in 1..10) {
                val resp = localClient.newCall(
                    Request.Builder().url("$uri/api/posts/1/like").post("".toRequestBody(jsonMt)).build()
                ).execute()
                resp.use {
                    assertThat(it.code).isEqualTo(200)
                }
            }
        } finally {
            s.stop()
            localClient.dispatcher.executorService.shutdown()
            localClient.connectionPool.evictAll()
        }
    }

    // ============ CORS 白名单 ============

    @Test
    fun `CORS - allowed origin gets Access-Control-Allow-Origin header`() {
        // 默认白名单包含 http://localhost:5173 (Vite)
        val req = Request.Builder()
            .url("$baseUri/api/posts/published?page=0&size=10")
            .header("Origin", "http://localhost:5173")
            .get()
            .build()
        val resp = client.newCall(req).execute()
        resp.use {
            assertThat(it.header("Access-Control-Allow-Origin")).isEqualTo("http://localhost:5173")
        }
    }

    @Test
    fun `CORS - disallowed origin does NOT get Access-Control-Allow-Origin header`() {
        val req = Request.Builder()
            .url("$baseUri/api/posts/published?page=0&size=10")
            .header("Origin", "https://evil.example.com")
            .get()
            .build()
        val resp = client.newCall(req).execute()
        resp.use {
            // 白名单之外的 origin 不返回 CORS allow 头
            assertThat(it.header("Access-Control-Allow-Origin")).isNull()
        }
    }

    @Test
    fun `docs - GET docs redirects 301 to docs index html`() {
        val noFollowClient = client.newBuilder().followRedirects(false).build()
        val req = Request.Builder().url("$baseUri/docs").get().build()
        val resp = noFollowClient.newCall(req).execute()
        resp.use {
            assertThat(it.code).isEqualTo(301)
            assertThat(it.header("Location")).isEqualTo("/docs/index.html")
        }
        noFollowClient.dispatcher.executorService.shutdown()
        noFollowClient.connectionPool.evictAll()
    }

    @Test
    fun `docs - GET docs index html serves Swagger UI HTML`() {
        val resp = get("/docs/index.html")
        resp.use {
            assertThat(it.code).isEqualTo(200)
            val body = it.body?.string() ?: ""
            assertThat(body).contains("swagger-ui")
            assertThat(body).contains("/openapi.json")
        }
    }

    private val jsonMt = "application/json; charset=utf-8".toMediaType()
}
