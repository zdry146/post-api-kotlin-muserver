/**
 * 运维端点集成测试 — 覆盖 OpenAPI spec, health liveness/readiness, RateLimit, CORS 白名单
 *
 * 跟 PostHandlerIntegrationTest 用同样的 OkHttp + H2 in-memory 模式，但只注册运维端点
 * 简化断言（CORS header, 429, JSON status 等）。
 */
class OperationalEndpointsTest {

    private lateinit var server: MuServer
    private lateinit var dataSource: DataSource
    private lateinit var client: OkHttpClient
    private lateinit var baseUri: String

    @BeforeEach
    fun setUp() {
        val h2Url = "jdbc:h2:mem:ops-${System.nanoTime()};DB_CLOSE_DELAY=-1"
        dataSource = DatabaseFactory.create(url = h2Url, user = "sa", password = "")
        initializeH2Schema(dataSource)

        val postRepository = PostRepository(dataSource)
        val postService = PostService(postRepository)
        val postHandler = PostHandler(postService)
        val cleanupJob = CleanupJob(postRepository)
        val adminHandler = AdminHandler(cleanupJob)
        val healthHandler = HealthHandler(dataSource)

        val builder = MuServerBuilder.httpServer().withHttpPort(0)
        builder.addHandler(CorsConfig.create())
        OpenApiHandler.register().forEach { builder.addHandler(it) }
        healthHandler.register().forEach { builder.addHandler(it) }
        DocsHandler.register().forEach { builder.addHandler(it) }
        val allRoutes = postHandler.register() + adminHandler.register()
        RequestLoggingHandler.wrapAll(allRoutes).forEach { builder.addHandler(it) }
        server = builder.start()
        baseUri = "http://localhost:${server.uri().port}"
        client = OkHttpClient.Builder().build()
    }

    private fun initializeH2Schema(ds: DataSource) {
        val ddl = """
            CREATE TABLE IF NOT EXISTS posts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title VARCHAR(200) NOT NULL,
                content CLOB NOT NULL,
                author_name VARCHAR(50) NOT NULL,
                cover_image VARCHAR(500),
                view_count BIGINT DEFAULT 0,
                like_count BIGINT DEFAULT 0,
                is_published BOOLEAN DEFAULT FALSE,
                is_deleted BOOLEAN DEFAULT FALSE,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
        """.trimIndent()
        ds.connection.use { it.createStatement().use { stmt -> stmt.execute(ddl) } }
    }

    @AfterEach
    fun tearDown() {
        server.stop()
        (dataSource as? com.zaxxer.hikari.HikariDataSource)?.close()
        client.dispatcher.executorService.shutdown()
        client.connectionPool.evictAll()
    }

    private fun get(path: String): Response = client.newCall(
        Request.Builder().url("$baseUri$path").get().build()
    ).execute()

    // ============ /openapi.json ============

    @Test
    fun `openapi json - 200 and serves spec with correct content type`() {
        val resp = get("/openapi.json")
        resp.use {
            assertThat(it.code).isEqualTo(200)
            assertThat(it.header("Content-Type")).contains("application/json")
            val body = it.body?.string() ?: ""
            assertThat(body).contains("\"openapi\"")
            assertThat(body).contains("\"paths\"")
            assertThat(body).contains("/api/posts")
        }
    }

    @Test
    fun `openapi json - CORS allow any origin (public spec)`() {
        val req = Request.Builder()
            .url("$baseUri/openapi.json")
            .header("Origin", "https://example.com")
            .get()
            .build()
        val resp = client.newCall(req).execute()
        resp.use {
            assertThat(it.code).isEqualTo(200)
            assertThat(it.header("Access-Control-Allow-Origin")).isEqualTo("https://example.com")
            assertThat(it.header("Cache-Control")).isEqualTo("public, max-age=300")
        }
    }

    @Test
    fun `openapi json - OPTIONS preflight returns 204`() {
        val req = Request.Builder()
            .url("$baseUri/openapi.json")
            .method("OPTIONS", null)
            .header("Origin", "https://example.com")
            .header("Access-Control-Request-Method", "GET")
            .build()
        val resp = client.newCall(req).execute()
        resp.use {
            assertThat(it.code).isEqualTo(204)
            assertThat(it.header("Access-Control-Allow-Methods")).contains("GET")
        }
    }

    // ============ /health ============

    @Test
    fun `health - 200 ok always`() {
        val resp = get("/health")
        resp.use {
            assertThat(it.code).isEqualTo(200)
            assertThat(it.header("Content-Type")).contains("application/json")
            val body = it.body?.string() ?: ""
            assertThat(body).contains("\"status\":\"ok\"")
        }
    }

    @Test
    fun `health ready - 200 ok when DB up`() {
        val resp = get("/health/ready")
        resp.use {
            assertThat(it.code).isEqualTo(200)
            val body = it.body?.string() ?: ""
            assertThat(body).contains("\"db\":\"up\"")
        }
